#!/usr/bin/env python3
"""Dialect fingerprint for MAVLink2 Devices (ModelViz Studio ADR-0009).

Computes, from a MAVLink dialect XML (following <include>s):
  * each Message's wire order, payload length and CRC_EXTRA, exactly as MAVLink2 defines them;
  * the dialect hash: FNV-1a 32-bit over one line per Message, sorted by id,
    "<id> <NAME> <crcExtra> <payloadLength>\\n".

The workbench computes the same hash and refuses telemetry until the Device reports it, so
firmware should embed the value generated here at build time (--c-header) instead of a
hand-copied constant.

Usage:
  dialect_hash.py dialects/bench.xml                  # print hash
  dialect_hash.py dialects/bench.xml --table          # also print per-Message details
  dialect_hash.py dialects/bench.xml --c-header out.h # write a C header for firmware
  dialect_hash.py dialects/bench.xml --json           # machine-readable output

Standard library only (Python 3.8+).
"""
import argparse
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

TYPE_SIZE = {
    "char": 1, "uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2,
    "uint32_t": 4, "int32_t": 4, "uint64_t": 8, "int64_t": 8, "float": 4, "double": 8,
}


def crc_accumulate(byte, crc):
    """CRC-16/MCRF4XX (MAVLink "X.25"), one byte."""
    tmp = (byte ^ (crc & 0xFF)) & 0xFF
    tmp = (tmp ^ (tmp << 4)) & 0xFF
    return ((crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4)) & 0xFFFF


def crc_string(s, crc=0xFFFF):
    for ch in s.encode("ascii"):
        crc = crc_accumulate(ch, crc)
    return crc


def parse_field(el, message):
    m = re.fullmatch(r"([a-z0-9_]+?)(?:\[(\d+)\])?", el.get("type", ""))
    if not m or not el.get("name"):
        raise SystemExit(f"Invalid field in {message}")
    ftype = "uint8_t" if m.group(1) == "uint8_t_mavlink_version" else m.group(1)
    if ftype not in TYPE_SIZE:
        raise SystemExit(f"Unknown field type {el.get('type')} in {message}")
    return {"name": el.get("name"), "type": ftype, "array": int(m.group(2) or 0)}


def parse_message(el):
    name, mid = el.get("name"), int(el.get("id"))
    base, ext, in_ext = [], [], False
    for child in el:
        if child.tag == "extensions":
            in_ext = True
        elif child.tag == "field":
            (ext if in_ext else base).append(parse_field(child, name))
    # wire order: base fields by element size, largest first, stable; extensions keep XML order
    ordered = sorted(base, key=lambda f: -TYPE_SIZE[f["type"]])
    crc = crc_string(name + " ")
    for f in ordered:
        crc = crc_string(f"{f['type']} {f['name']} ", crc)
        if f["array"]:
            crc = crc_accumulate(f["array"], crc)
    length = sum(TYPE_SIZE[f["type"]] * max(1, f["array"]) for f in ordered + ext)
    if length > 255:
        raise SystemExit(f"Message {name} payload exceeds 255 bytes ({length})")
    return {
        "id": mid,
        "name": name,
        "crc_extra": ((crc & 0xFF) ^ (crc >> 8)) & 0xFF,
        "payload_length": length,
        "wire_order": [f["name"] for f in ordered + ext],
    }


def load(path, messages, seen):
    path = os.path.abspath(path)
    if path in seen:
        return
    seen.add(path)
    root = ET.parse(path).getroot()
    if root.tag != "mavlink":
        raise SystemExit(f"Not a MAVLink dialect: {path}")
    for inc in root.findall("include"):
        load(os.path.join(os.path.dirname(path), inc.text.strip()), messages, seen)
    for el in root.findall("messages/message"):
        msg = parse_message(el)
        old = messages.get(msg["id"])
        if old and old["name"] != msg["name"]:
            raise SystemExit(f"Message id {msg['id']} defined twice ({old['name']}, {msg['name']})")
        messages[msg["id"]] = msg


def dialect_hash(messages):
    h = 0x811C9DC5
    for m in messages:
        for ch in f"{m['id']} {m['name']} {m['crc_extra']} {m['payload_length']}\n".encode("ascii"):
            h ^= ch
            h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def c_header(path, h, messages):
    guard = "DIALECT_HASH_H"
    lines = [
        f"/* Generated by dialect_hash.py from {os.path.basename(path)}. Do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "/* Report this in DIALECT_INFO.hash; the workbench refuses telemetry until it matches. */",
        f"#define DIALECT_HASH 0x{h:08x}u",
        "",
    ]
    for m in messages:
        lines.append(f"/* {m['id']:>8} {m['name']:<24} crc_extra={m['crc_extra']:>3} len={m['payload_length']} */")
    lines += ["", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dialect")
    ap.add_argument("--table", action="store_true", help="print per-Message id, CRC_EXTRA, length and wire order")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--c-header", metavar="PATH", help="write a C header defining DIALECT_HASH")
    args = ap.parse_args()

    found = {}
    load(args.dialect, found, set())
    messages = [found[k] for k in sorted(found)]
    h = dialect_hash(messages)

    if args.c_header:
        with open(args.c_header, "w") as f:
            f.write(c_header(args.dialect, h, messages))
    if args.json:
        json.dump({"hash": f"{h:08x}", "hash_uint32": h, "messages": messages}, sys.stdout, indent=2)
        print()
        return
    print(f"{h:08x}  (uint32 {h})")
    if args.table:
        for m in messages:
            print(f"{m['id']:>8}  {m['name']:<24} crc_extra={m['crc_extra']:>3}  len={m['payload_length']:>3}  {', '.join(m['wire_order'])}")


if __name__ == "__main__":
    main()
